export interface PromptSource {
  n: number
  title: string
  origin: string
  text: string
}

export function formatSources(sources: PromptSource[]): string {
  if (!sources.length) return 'Источники: (ничего не найдено)'
  return `Источники:\n${sources
    .map(s => `[${s.n}] ${s.title} (автор: ${s.origin})\n${s.text}`)
    .join('\n\n')}`
}

export function buildAssistantUserPrompt(
  question: string,
  sources: PromptSource[],
  learner: string,
  personalShown = false,
): string {
  // Профиль перед источниками: модель воспроизводит порядок блоков контекста.
  const about = personalShown
    ? 'Персональную часть (что студент освоил и где ошибался) уже показали ему отдельно. Не пиши о его прогрессе, ответь только по материалам: что о теме говорят источники.\n\n'
    : learner ? `О студенте:\n${learner}\n\n` : ''
  return `${about}${formatSources(sources)}

Вопрос студента: ${question}`
}

