/** Нормализация, стоп-слова и стемминг окончаний (ru/en) для BM25. */

const STOP_WORDS = new Set(
  (
    'и в во не что он на я с со как а то все она так его но да ты к у же вы за бы по только ее мне было вот от меня еще нет о из ему теперь когда даже ну вдруг ли если уже или ни быть был него до вас нибудь опять уж вам ведь там потом себя ничего ей может они тут где есть надо ней для мы тебя их чем была сам чтоб без будто чего раз тоже себе под будет ж тогда кто этот того потому этого какой совсем ним здесь этом один почти мой тем чтобы нее сейчас были куда зачем всех никогда можно при наконец два об другой хоть после над больше тот через эти нас про всего них какая много разве три эту моя впрочем хорошо свою этой перед иногда лучше чуть том нельзя такой им более всегда конечно всю между это эта также ещё мои мой моих мне меня я ли' +
    ' the a an of to in on for is are be and or with as by it this that what how why which'
  ).split(/\s+/),
)

// От длинных к коротким: отрезается первое подходящее.
const RU_ENDINGS = [
  'иями', 'ями', 'ами', 'ией', 'иях', 'ях', 'ах', 'ого', 'его', 'ому', 'ему', 'ыми', 'ими',
  'ую', 'юю', 'ая', 'яя', 'ое', 'ее', 'ые', 'ие', 'ый', 'ий', 'ой', 'ей', 'ов', 'ев', 'ия',
  'ть', 'ет', 'ут', 'ют', 'ит', 'ат', 'ят', 'ем', 'им', 'ом', 'ам', 'ям', 'ах',
  'а', 'я', 'о', 'е', 'ы', 'и', 'у', 'ю', 'ь', 'й',
]

function stemRu(word: string): string {
  if (word.length <= 4) return word
  for (const end of RU_ENDINGS) {
    if (word.endsWith(end) && word.length - end.length >= 3) {
      return word.slice(0, -end.length)
    }
  }
  return word
}

function stemEn(word: string): string {
  if (word.length <= 4) return word
  return word.replace(/(ies|ing|ed|es|s)$/, '')
}

export function tokenize(text: string): string[] {
  const words = text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .split(/[^a-zа-я0-9]+/u)
    .filter(w => w.length > 1 && !STOP_WORDS.has(w))
  return words.map(w => (/[а-я]/.test(w) ? stemRu(w) : stemEn(w)))
}
